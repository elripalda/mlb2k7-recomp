#!/usr/bin/env python3
"""Find code the ReXGlue recompiler left out, and write [functions] entries for it.

When a function is only reached through a pointer (vtables, callbacks, this-adjust
thunks), the analyzer can fold it into the function before it and never emit it.
The game then dies with "Call to invalid or unregistered function at guest address X".

This scans the generated C++ for every function's last emitted instruction and
reports code between that and the next function's start.

Usage:
  find_missing_functions.py <project>/generated/default [existing_functions.toml] [--code-end 0x8XXXXXXX]

Writes the merged list to stdout. Save it as your project's functions toml, run
REBUILD, test, and repeat: each pass can uncover more (gaps holding several tiny
functions are split one at a time).
"""
import glob
import re
import sys

args = [a for a in sys.argv[1:] if not a.startswith('--')]
code_end = None
if '--code-end' in sys.argv:
    code_end = int(sys.argv[sys.argv.index('--code-end') + 1], 16)
gen = args[0]
existing = args[1] if len(args) > 1 else None

func_re = re.compile(r'^DEFINE_REX_FUNC\(sub_([0-9A-F]{8})\)')
label_re = re.compile(r'^loc_([0-9A-F]{8}):')
instr_re = re.compile(r'^\t// (\S+)')

# Last emitted address per function (re-anchored at every label, so chunked
# functions are measured correctly).
funcs = {}
for path in glob.glob(gen + '/*_recomp.*.cpp'):
    cur = None
    for line in open(path, errors='replace'):
        m = func_re.match(line)
        if m:
            cur = int(m.group(1), 16)
            pc = cur
            funcs[cur] = [cur, None]
            continue
        if cur is None:
            continue
        m = label_re.match(line)
        if m:
            pc = int(m.group(1), 16)
            continue
        m = instr_re.match(line)
        if m:
            pc += 4
            if pc > funcs[cur][0]:
                funcs[cur] = [pc, m.group(1)]

hdr = glob.glob(gen + '/*_funcs.h')
starts = sorted(set(int(x, 16) for h in hdr for x in re.findall(r'sub_([0-9A-F]{8})', open(h).read())))
if code_end is None:
    code_end = starts[-1] + 0x100000  # unknown: the last gap is skipped below anyway

entries = {}
not_code = set()  # addresses already found to be data; never add them again
if existing:
    for l in open(existing):
        m = re.match(r'# not code: 0x([0-9A-Fa-f]{8})', l)
        if m:
            not_code.add(int(m.group(1), 16))
            continue
        m = re.match(r'0x([0-9A-Fa-f]{8}) = \{ end = 0x([0-9A-Fa-f]{8}) \}', l)
        if m:
            entries[int(m.group(1), 16)] = int(m.group(2), 16)
            continue
        m = re.match(r'0x([0-9A-Fa-f]{8}) = \{\}', l)
        if m:
            entries[int(m.group(1), 16)] = None

added, dropped = [], []
for i, s in enumerate(starts):
    nxt = starts[i + 1] if i + 1 < len(starts) else None
    if nxt is None or s not in funcs:
        continue
    end, last = funcs[s]
    if last is None:
        # An entry that produced no code: it was data or padding, not a function.
        if s in entries:
            del entries[s]
            dropped.append(s)
            not_code.add(s)
            for k, v in list(entries.items()):
                if v == s:
                    entries[k] = None  # its parent no longer ends there
        continue
    if nxt - end < 8 or last == 'bl':
        continue  # 4-byte gaps are alignment padding; after 'bl' it's usually padding too
    start = (end + 7) & ~7  # functions here are 8-byte aligned
    if start >= nxt or start in not_code:
        continue
    entries[s] = start
    if last == 'b' and end - s == 8:
        # A run of 8-byte "adjust this, jump" thunks: split them all.
        a = start
        while a < nxt and a not in not_code:
            entries[a] = a + 8 if a + 8 < nxt else None
            added.append(a)
            a += 8
    else:
        entries.setdefault(start, None)
        added.append(start)

print('# Function boundaries the analyzer got wrong. Generated by find_missing_functions.py.')
for a in sorted(not_code):
    print(f'# not code: 0x{a:08X}')
print('[functions]')
for a in sorted(entries):
    e = entries[a]
    print(f'0x{a:08X} = {{ end = 0x{e:08X} }}' if e else f'0x{a:08X} = {{}}')
print(f'# {len(added)} new, {len(dropped)} dropped, {len(entries)} total', file=sys.stderr)
